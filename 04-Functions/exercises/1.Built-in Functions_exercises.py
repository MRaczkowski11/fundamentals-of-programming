# 1. Program for testing built-in functions======================================================================================================================================================================

max_number = max(7, 5, 6, 3, 8, 2)                          # Finding the largest number
print('Max number of 7,5,6,3,8,2 is', max_number)

min_number = min(4, 7, 2, 3, 9, 8)                          # Finding the smallest number
print('Min number of 4,7,2,3,9,8 is', min_number)

str_length = len("computer science")                       # Counting the number of characters
print('The number of characters in "computer science" is', str_length)

letter = input('Enter a letter: ')                          # Reading a letter from the keyboard
print('The entered letter is', letter)

number = int("20303")                                       # Converting a string to an integer
print('The integer number is', number)

binary_number = bin(304)                                    # Converting a decimal number to binary
print('The binary number of 304 is', binary_number)

hex_number = hex(304)                                       # Converting a decimal number to hexadecimal
print('The hexadecimal number of 304 is', hex_number)

unicode_number = ord('€')                                   # Getting the Unicode code of the euro sign
print('The Unicode code of € is', unicode_number)

absolute_number = abs(-17)                                  # Calculating the absolute value
print('The absolute value of -17 is', absolute_number)

